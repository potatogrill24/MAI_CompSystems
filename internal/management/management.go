func Routes(ctx context.Context, db *pgxpool.Pool) (http.Handler, error) {
	_, err := db.Exec(ctx, `CREATE TABLE IF NOT EXISTS projects(id BIGSERIAL PRIMARY KEY, data JSONB NOT NULL)`)
	if err != nil {
		return nil, err
	}
	mux := http.NewServeMux()
	httpx.Health(mux, db.Ping)
	mux.HandleFunc("POST /projects", func(w http.ResponseWriter, r *http.Request) {
		var p model.Project
		if !httpx.Decode(w, r, &p) {
			return
		}
		if !httpx.Text(p.OrderName) || !httpx.Date(p.StartDate) || len(p.Works) > 0 || p.ID != 0 {
			httpx.Error(w, 400, "order_name and start_date required; add works separately")
			return
		}
		p.Works = []model.Work{}
		raw, _ := json.Marshal(p)
		err := db.QueryRow(r.Context(), "INSERT INTO projects(data) VALUES($1) RETURNING id", raw).Scan(&p.ID)
		if err != nil {
			httpx.Internal(w, err)
			return
		}
		w.Header().Set("Location", fmt.Sprintf("/projects/%d", p.ID))
		httpx.JSON(w, 201, p)
	})
	mux.HandleFunc("GET /projects", func(w http.ResponseWriter, r *http.Request) {
		rows, err := db.Query(r.Context(), "SELECT id,data FROM projects ORDER BY id")
		if err != nil {
			httpx.Internal(w, err)
			return
		}
		defer rows.Close()
		list := []model.Project{}
		for rows.Next() {
			var id int
			var raw []byte
			if err = rows.Scan(&id, &raw); err != nil {
				break
			}
			var p model.Project
			if err = json.Unmarshal(raw, &p); err != nil {
				break
			}
			p.ID = id
			list = append(list, p)
		}
		if err == nil {
			err = rows.Err()
		}
		if err != nil {
			httpx.Internal(w, err)
			return
		}
		httpx.JSON(w, 200, list)
	})
	mux.HandleFunc("GET /projects/{id}", func(w http.ResponseWriter, r *http.Request) {
		p, err := load(r.Context(), db, r.PathValue("id"))
		if err != nil {
			failure(w, err)
			return
		}
		httpx.JSON(w, 200, p)
	})
	mux.HandleFunc("DELETE /projects/{id}", func(w http.ResponseWriter, r *http.Request) {
		id, err := parseID(r.PathValue("id"))
		if err != nil {
			failure(w, err)
			return
		}
		tag, err := db.Exec(r.Context(), "DELETE FROM projects WHERE id=$1", id)
		if err != nil {
			httpx.Internal(w, err)
			return
		}
		if tag.RowsAffected() == 0 {
			httpx.Error(w, 404, "project not found")
			return
		}
		w.WriteHeader(204)
	})
	edit := func(w http.ResponseWriter, r *http.Request) {
		var in struct {
			OrderName *string `json:"order_name"`
			StartDate *string `json:"start_date"`
		}
		if !httpx.Decode(w, r, &in) {
			return
		}
		if in.OrderName == nil && in.StartDate == nil {
			httpx.Error(w, 400, "no fields to update")
			return
		}
		mutate(w, r, db, func(p *model.Project) (any, error) {
			if in.OrderName != nil {
				if !httpx.Text(*in.OrderName) {
					return nil, errors.New("invalid order_name")
				}
				p.OrderName = *in.OrderName
			}
			if in.StartDate != nil {
				if !httpx.Date(*in.StartDate) {
					return nil, errors.New("invalid start_date")
				}
				p.StartDate = *in.StartDate
			}
			return p, nil
		}, 200)
	}
	mux.HandleFunc("PATCH /projects/{id}", edit)
	mux.HandleFunc("PUT /projects/{id}", edit)
	mux.HandleFunc("POST /projects/{id}/works", func(w http.ResponseWriter, r *http.Request) {
		var in model.Work
		if !httpx.Decode(w, r, &in) {
			return
		}
		if in.ID != 0 {
			httpx.Error(w, 400, "id is generated by server")
			return
		}
		mutate(w, r, db, func(p *model.Project) (any, error) {
			for _, work := range p.Works {
				in.ID = max(in.ID, work.ID)
			}
			in.ID++
			if in.Pred == nil {
				in.Pred = []int{}
			}
			if !httpx.Text(in.Task) {
				return nil, errors.New("task is required and limited to 255 characters")
			}
			p.Works = append(p.Works, in)
			if err := scheduler.Validate(p.Works); err != nil {
				return nil, err
			}
			return in, nil
		}, 201)
	})
	mux.HandleFunc("DELETE /projects/{id}/works/{work}", func(w http.ResponseWriter, r *http.Request) {
		workID, err := parseID(r.PathValue("work"))
		if err != nil {
			failure(w, err)
			return
		}
		mutate(w, r, db, func(p *model.Project) (any, error) {
			index := -1
			for i, work := range p.Works {
				if work.ID == workID {
					index = i
				}
				for _, pred := range work.Pred {
					if pred == workID {
						return nil, errors.New("work is referenced by another work; remove the dependency first")
					}
				}
			}
			if index < 0 {
				return nil, pgx.ErrNoRows
			}
			p.Works = append(p.Works[:index], p.Works[index+1:]...)
			return nil, nil
		}, 204)
	})
	setPred := func(w http.ResponseWriter, r *http.Request) {
		workID, err := parseID(r.PathValue("work"))
		if err != nil {
			failure(w, err)
			return
		}
		var in struct {
			Pred *[]int `json:"pred"`
		}
		if !httpx.Decode(w, r, &in) {
			return
		}
		if in.Pred == nil {
			httpx.Error(w, 400, "pred array required")
			return
		}
		mutate(w, r, db, func(p *model.Project) (any, error) {
			for i := range p.Works {
				if p.Works[i].ID == workID {
					p.Works[i].Pred = *in.Pred
					if err := scheduler.Validate(p.Works); err != nil {
						return nil, err
					}
					return p.Works[i], nil
				}
			}
			return nil, pgx.ErrNoRows
		}, 200)
	}
	mux.HandleFunc("PUT /projects/{id}/works/{work}/predecessors", setPred)
	mux.HandleFunc("POST /projects/{id}/works/{work}/predecessors", setPred)
	calcClient := &http.Client{Timeout: 125 * time.Second}
	mux.HandleFunc("POST /projects/{id}/calculate", func(w http.ResponseWriter, r *http.Request) {
		p, err := load(r.Context(), db, r.PathValue("id"))
		if err != nil {
			failure(w, err)
			return
		}
		var in struct {
			Iterations int    `json:"iterations"`
			Workers    int    `json:"workers"`
			Seed       uint64 `json:"seed"`
		}
		if !httpx.Decode(w, r, &in) {
			return
		}
		raw, _ := json.Marshal(scheduler.Request{Works: p.Works, Iterations: in.Iterations, Workers: in.Workers, Seed: in.Seed})
		req, err := http.NewRequestWithContext(r.Context(), "POST", httpx.Env("CALCULATOR_URL", "http://localhost:8082")+"/calculate", bytes.NewReader(raw))
		if err != nil {
			httpx.Internal(w, err)
			return
		}
		req.Header.Set("Content-Type", "application/json")
		resp, err := calcClient.Do(req)
		if err != nil {
			httpx.Error(w, 502, "calculator unavailable")
			return
		}
		defer resp.Body.Close()
		var result any
		if err = json.NewDecoder(resp.Body).Decode(&result); err != nil {
			httpx.Error(w, 502, "invalid calculator response")
			return
		}
		httpx.JSON(w, resp.StatusCode, result)
	})
	return httpx.Wrap(mux), nil
}

type querier interface {
	QueryRow(context.Context, string, ...any) pgx.Row
}

func parseID(s string) (int, error) {
	id, err := strconv.Atoi(s)
	if err != nil || id <= 0 {
		return 0, errors.New("invalid id")
	}
	return id, nil
}
func load(ctx context.Context, db querier, s string) (model.Project, error) {
	id, err := parseID(s)
	if err != nil {
		return model.Project{}, err
	}
	var raw []byte
	err = db.QueryRow(ctx, "SELECT data FROM projects WHERE id=$1", id).Scan(&raw)
	var p model.Project
	if err == nil {
		err = json.Unmarshal(raw, &p)
		p.ID = id
	}
	return p, err
}
func failure(w http.ResponseWriter, err error) {
	if errors.Is(err, pgx.ErrNoRows) {
		httpx.Error(w, 404, "project or work not found")
	} else if err.Error() == "invalid id" {
		httpx.Error(w, 400, err.Error())
	} else {
		httpx.Internal(w, err)
	}
}
func mutate(w http.ResponseWriter, r *http.Request, db *pgxpool.Pool, fn func(*model.Project) (any, error), status int) {
	id, err := parseID(r.PathValue("id"))
	if err != nil {
		failure(w, err)
		return
	}
	tx, err := db.Begin(r.Context())
	if err != nil {
		httpx.Internal(w, err)
		return
	}
	defer tx.Rollback(r.Context())
	var raw []byte
	err = tx.QueryRow(r.Context(), "SELECT data FROM projects WHERE id=$1 FOR UPDATE", id).Scan(&raw)
	if err != nil {
		failure(w, err)
		return
	}
	var p model.Project
	if err = json.Unmarshal(raw, &p); err != nil {
		httpx.Internal(w, err)
		return
	}
	p.ID = id
	out, err := fn(&p)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			failure(w, err)
		} else {
			httpx.Error(w, 400, err.Error())
		}
		return
	}
	raw, _ = json.Marshal(p)
	_, err = tx.Exec(r.Context(), "UPDATE projects SET data=$1 WHERE id=$2", raw, id)
	if err == nil {
		err = tx.Commit(r.Context())
	}
	if err != nil {
		httpx.Internal(w, err)
		return
	}
	httpx.JSON(w, status, out)
}

// Calculator admits one search at a time; work inside it uses a bounded worker pool.
func Calculator() http.Handler {
	mux := http.NewServeMux()
	httpx.Health(mux, nil)
	var gate sync.Mutex
	mux.HandleFunc("POST /calculate", func(w http.ResponseWriter, r *http.Request) {
		var in scheduler.Request
		if !httpx.Decode(w, r, &in) {
			return
		}
		if err := scheduler.Validate(in.Works); err != nil {
			httpx.Error(w, 400, err.Error())
			return
		}
		if !gate.TryLock() {
			httpx.Error(w, 429, "calculator is busy")
			return
		}
		defer gate.Unlock()
		ctx, cancel := context.WithTimeout(r.Context(), 120*time.Second)
		defer cancel()
		result, err := scheduler.Calculate(ctx, in)
		if err != nil {
			status := 400
			if errors.Is(err, context.DeadlineExceeded) || errors.Is(err, context.Canceled) {
				status = 408
			}
			httpx.Error(w, status, err.Error())
			return
		}
		httpx.JSON(w, 200, result)
	})
	return httpx.Wrap(mux)
}
